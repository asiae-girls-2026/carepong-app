/** API 결과에 시나리오 답변이 없을 때 쓰는 템플릿 (LLM 자리) */
export function templateBboong(name: string, efficacy: string): string {
  const firstSentence = efficacy.split(/[.\n]/)[0].trim()
  return `${name.replace(/정$|캡슐$|시럽$/, '')}에 대해 찾아봤어! 핵심만 말하면 ${firstSentence}에 쓰는 약이야. 자세한 복용법은 카드를 확인해줘. 몸 상태가 계속 안 좋으면 꼭 약사님이나 의사선생님께 물어보라퐁!`
}

export function searchMock(query: string): DrugInfo[] {
  const q = query.replace(/\s/g, '').toLowerCase()
  return MOCK_DRUGS.filter((d) => d.name.replace(/\s/g, '').toLowerCase().includes(q))
}
